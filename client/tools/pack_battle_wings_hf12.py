"""Lossless trim of transparent atlas margins, retaining each original frame anchor."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
tables=[]
for s in (1,2):
    table=[]; before=after=0
    for wing in range(6):
        for angle in range(5):
            for layer in range(2):
                base=root/('assets%d'%s)
                source=Image.open(base/('wing795-game-%d-%d-%d.png'%(wing,angle,layer))).convert('RGBA')
                side=96*s
                assert source.size==(side*19,side)
                frames=[source.crop((i*side,0,(i+1)*side,side)) for i in range(19)]
                boxes=[f.getchannel('A').getbbox() for f in frames]
                boxes=[b for b in boxes if b]
                x0=min(b[0] for b in boxes)//s*s;y0=min(b[1] for b in boxes)//s*s
                x1=(max(b[2] for b in boxes)+s-1)//s*s;y1=(max(b[3] for b in boxes)+s-1)//s*s
                w=x1-x0;h=y1-y0
                packed=Image.new('RGBA',(w*19,h))
                for i,f in enumerate(frames):
                    cell=f.crop((x0,y0,x1,y1));packed.paste(cell,(i*w,0))
                    restored=Image.new('RGBA',(side,side));restored.paste(cell,(x0,y0))
                    # Invisible RGB values are immaterial; all alpha and visible RGB must agree.
                    assert restored.getchannel('A').tobytes()==f.getchannel('A').tobytes()
                    assert restored.tobytes()==f.tobytes() or all(a==b or (a[3]==0 and b[3]==0) for a,b in zip(restored.getdata(),f.getdata()))
                packed.save(base/('wing812-packed-%d-%d-%d.png'%(wing,angle,layer)),optimize=True)
                table.extend([x0//s,y0//s,w//s,h//s]);before+=source.width*source.height*4;after+=packed.width*packed.height*4
    tables.append(table)
    print('scale %d: %d -> %d decoded bytes, %.1f%% saved'%(s,before,after,100*(1-after/before)))
code='''// Generated by tools/pack_battle_wings_hf12.py. Logical bounds, preserving anchors.
final class WingBattleArt {
'''
for s,table in enumerate(tables,1):
    code+='    static final int[] BOUNDS%d = {\n'%s
    for i in range(0,len(table),20):code+='        '+', '.join(map(str,table[i:i+20]))+(',\n' if i+20<len(table) else '\n')
    code+='    };\n'
code+='''    static int[] bounds(int scale) { return scale == 2 ? BOUNDS2 : BOUNDS1; }
    static int index(int wing,int angle,int layer) { return ((wing*5+angle)*2+layer)*4; }
    static int bytes(int scale,int wing,int angle) {
        int[] b=bounds(scale);int i=index(wing,angle,0);
        return (b[i+2]*b[i+3]+b[i+6]*b[i+7])*19*4*scale*scale;
    }
    static int nearest(int mask,int requested) {
        if((mask&(1<<requested))!=0)return requested;
        for(int d=1;d<5;d++){
            if(requested-d>=0&&(mask&(1<<(requested-d)))!=0)return requested-d;
            if(requested+d<5&&(mask&(1<<(requested+d)))!=0)return requested+d;
        }
        return -1;
    }
}
'''
(root/'src/WingBattleArt.java').write_text(code,encoding='utf-8')

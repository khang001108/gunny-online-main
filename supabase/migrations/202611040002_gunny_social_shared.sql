create unique index if not exists gunny_public_id on public.profiles(public_id);
create table if not exists public.gunny_friends(sender uuid not null references public.profiles(id) on delete cascade,receiver uuid not null references public.profiles(id) on delete cascade,accepted boolean not null default false,primary key(sender,receiver),check(sender<>receiver));
create unique index if not exists gunny_friend_pair on public.gunny_friends(least(sender,receiver),greatest(sender,receiver));
alter table public.gunny_friends enable row level security;
revoke all on public.gunny_friends from public,anon,authenticated;

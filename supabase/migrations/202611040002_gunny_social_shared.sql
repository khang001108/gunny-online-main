grant usage,select on all sequences in schema public to service_role;
create or replace function public.gunny_friend_action(p_user uuid,p_target integer,p_mode integer) returns void language plpgsql security definer set search_path='' as $$
declare target uuid;
begin
 select id into strict target from public.profiles where public_id=p_target;
 if target=p_user then raise exception 'Cannot add self';end if;
 if p_mode=0 then
 insert into public.gunny_friends(sender,receiver) values(p_user,target) on conflict do nothing;
 elsif p_mode=1 then
 update public.gunny_friends set accepted=true where sender=target and receiver=p_user and not accepted;
 if not found then raise exception 'No pending request';end if;
 elsif p_mode=2 then delete from public.gunny_friends where sender=target and receiver=p_user and not accepted;
 else raise exception 'Invalid action';end if;
end;$$;
revoke all on function public.gunny_friend_action(uuid,integer,integer) from public,anon,authenticated;
grant execute on function public.gunny_friend_action(uuid,integer,integer) to service_role;
create or replace function public.gunny_claim_card(p_match uuid,p_user uuid,p_card integer,p_coins integer)
returns jsonb language plpgsql security definer set search_path='' as $$
declare r public.card_rewards; n integer;
begin
 if p_card not between 0 and 8 or p_coins not between 50 and 200 then raise exception 'Invalid reward';end if;
 if not exists(select 1 from public.match_results where id=p_match and players @> jsonb_build_array(jsonb_build_object('id',p_user::text))) then raise exception 'Not a participant';end if;
 -- Serialize the entire shared board, including concurrent requests.
 perform 1 from public.match_results where id=p_match for update;
 perform 1 from public.profiles where id=p_user for update;
 select * into r from public.card_rewards where match_id=p_match and user_id=p_user;
 if found then return jsonb_build_object('card',r.card,'coins',r.coins);end if;
 if exists(select 1 from public.card_rewards where match_id=p_match and card=p_card) then raise exception 'Card already taken';end if;
 insert into public.card_rewards(match_id,user_id,card,coins) values(p_match,p_user,p_card,p_coins);
 update public.profiles set coins=least(999999,coins+p_coins) where id=p_user;
 return jsonb_build_object('card',p_card,'coins',p_coins);
end;$$;
revoke all on function public.gunny_claim_card(uuid,uuid,integer,integer) from public,anon,authenticated;
grant execute on function public.gunny_claim_card(uuid,uuid,integer,integer) to service_role;
